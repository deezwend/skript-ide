/** Üretilen dosyaların ilk satırındaki işaret; yalnızca bu işareti taşıyan dosyaların üzerine yazılır. */
export const SCRIPT_MARKER = 'generated by Skript IDE (display_geometry)'
const MAX_VALUE_ROWS = 300

interface SceneInput {
  shapes: RawShape[]
  block?: string
  thickness?: number
  width?: number
  tolerance?: number
}

const vec3: JsonSchema = { type: 'array', items: { type: 'number' }, description: '[x, y, z] in blocks, relative to the drawing origin (+y up).' }
const points: JsonSchema = { type: 'array', items: { type: 'array', items: { type: 'number' } } }

const shapeSchema: JsonSchema = {
  type: 'object',
  description: 'One shape; which fields apply depends on type.',
  properties: {
    type: {
      type: 'string',
      enum: ['box', 'line', 'polyline', 'triangle', 'polygon', 'circle', 'curve', 'cylinder', 'sphere', 'mesh', 'obj'],
      description:
        'box: center+size (or from+to corners), optional axis+angle rotation. line: from→to bar. polyline: points, optional closed. ' +
        'triangle: 3 points, filled. polygon: planar points, filled (fill=false draws the outline). ' +
        'circle: center+radius (radius2 for an ellipse), normal (default [0,1,0] = lying flat), optional start_angle/end_angle arc, fill. ' +
        'curve: Bezier through control points (any degree). cylinder: from, to, radius, caps. sphere: center, radius. ' +
        'mesh: vertices + faces (0-based index lists). obj: path to a Wavefront .obj in the project, optional scale/offset/axis+angle.'
    },
    block: { type: 'string', description: 'Block id with optional state, e.g. red_concrete or oak_stairs[facing=north].' },
    points,
    from: vec3,
    to: vec3,
    center: vec3,
    size: vec3,
    normal: vec3,
    axis: vec3,
    angle: { type: 'number', description: 'Rotation around axis in degrees (right-hand rule); axis defaults to [0,1,0].' },
    radius: { type: 'number' },
    radius2: { type: 'number', description: 'Second radius (ellipse), along the 90° direction.' },
    start_angle: { type: 'number', description: 'Degrees. 0° is +x for a flat circle (normal ±y), and angles turn from +x towards -z.' },
    end_angle: { type: 'number', description: 'Degrees, default start_angle + 360.' },
    fill: { type: 'boolean' },
    closed: { type: 'boolean' },
    caps: { type: 'boolean', description: 'cylinder: close both ends (default true).' },
    cap: { type: 'string', enum: ['flat', 'square'], description: 'Open line ends: flat (default) or extended by half the width.' },
    width: { type: 'number', description: 'Line/bar thickness in blocks.' },
    thickness: { type: 'number', description: 'Plate thickness in blocks for filled surfaces.' },
    tolerance: { type: 'number', description: 'Maximum distance between a curved shape and its flat approximation, in blocks.' },
    vertices: points,
    faces: points,
    path: { type: 'string' },
    scale: { type: 'number' },
    offset: vec3
  },
  required: ['type'],
  additionalProperties: false
}

const sceneProperties: Record<string, JsonSchema> = {
  shapes: { type: 'array', items: shapeSchema, description: 'The shapes to draw.' },
  block: { type: 'string', description: `Default block (${DEFAULTS.block}).` },
  thickness: { type: 'number', description: `Default plate thickness (${DEFAULTS.thickness}).` },
  width: { type: 'number', description: `Default line width (${DEFAULTS.width}).` },
  tolerance: { type: 'number', description: `Default curve tolerance in blocks (${DEFAULTS.tolerance}).` }
}

async function compile(input: SceneInput, ctx: ToolContext): Promise<{ scene: CompiledScene; plan: DisplayPlan }> {
  try {
    const scene = await compileScene(input, {
      loadObj: async (path) => {
        const file = await resolveInProject(ctx, path)
        return parseObj(await readFile(file, 'utf8'))
      }
    })
    return { scene, plan: planDisplays(scene.parts) }
  } catch (error) {
    if (error instanceof GeometryError) throw new ToolError(error.message)
    throw error
  }
}

function report(scene: CompiledScene, plan: DisplayPlan): string[] {
  const min: [number, number, number] = [Infinity, Infinity, Infinity]
  const max: [number, number, number] = [-Infinity, -Infinity, -Infinity]
  for (const part of scene.parts) {
    for (const corner of partCorners(part)) {
      for (let i = 0; i < 3; i++) {
        min[i] = Math.min(min[i], corner[i])
        max[i] = Math.max(max[i], corner[i])
      }
    }
  }
  const v = (p: Vec3): string => `(${p.map((n) => formatNumber(n, 4)).join(', ')})`
  return [
    `${plan.transforms.length} block displays. Max corner error after float rounding: ${plan.maxError.toExponential(1)} blocks.`,
    `Bounding box relative to the origin: ${v(min)} to ${v(max)}.`,
    ...scene.summary,
    ...scene.warnings.map((warning) => `Warning: ${warning}`)
  ]
}

export const displayGeometryTool = defineTool<SceneInput & { values?: boolean }>({
  name: 'display_geometry',
  description:
    'Compute exact Minecraft block display transformations for a drawing described as shapes (lines, polygons, circles, ' +
    'curves, boxes, cylinders, spheres, meshes, .obj models). Every shape is reduced to boxes and triangles, decomposed ' +
    'exactly (SVD, so slanted/sheared plates are exact) and each display is verified corner by corner. ' +
    'Use it to check a drawing (display count, bounding box, warnings) before writing it with write_display_script, ' +
    'or with values=true to get raw translation/left_rotation/scale/right_rotation numbers. Never compute these numbers yourself.',
  inputSchema: {
    type: 'object',
    properties: {
      ...sceneProperties,
      values: { type: 'boolean', description: 'Also list every display\'s transformation values.' }
    },
    required: ['shapes'],
    additionalProperties: false
  },
  permission: 'read',
  async execute(input, ctx) {
    const { scene, plan } = await compile(input, ctx)
    const lines = report(scene, plan)
    if (input.values) {
      const rows = transformsTable(plan).split('\n')
      lines.push('', ...rows.slice(0, MAX_VALUE_ROWS))
      if (rows.length > MAX_VALUE_ROWS) lines.push(`… ${rows.length - MAX_VALUE_ROWS} more; use write_display_script for the full drawing.`)
    }
    return lines.join('\n')
  }
})

/**
 * Hedef dosyanın içeriği; yoksa `null`. Elle yazılmış bir dosyanın üzerine yazılmaz; kullanıcının
 * çizim için açtığı boş dosya ise yeni dosya sayılır.
 */
async function generatedTarget(ctx: ToolContext, path: string, marker: string): Promise<{ file: string; before: string | null }> {
  if (!path.endsWith('.sk')) throw new ToolError('path must be a .sk file.')
  const file = await resolveTargetInProject(ctx, path)
  let before: string | null = null
  try {
    if ((await stat(file)).isDirectory()) throw new ToolError(`${path} is a directory.`)
    before = await readFile(file, 'utf8')
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error
  }
  if (before !== null && before.trim() !== '' && !before.split('\n', 1)[0].includes(marker)) {
    throw new ToolError(`${path} exists and was not generated by this tool; choose a new file so hand-written code is not overwritten.`)
  }
  return { file, before }
}

interface WriteScriptInput extends SceneInput {
  path: string
  function_name: string
  description?: string
}

async function buildScript(input: WriteScriptInput, ctx: ToolContext): Promise<{ content: string; summary: string[] }> {
  try {
    checkFunctionName(input.function_name)
  } catch (error) {
    throw new ToolError((error as Error).message)
  }
  const { scene, plan } = await compile(input, ctx)
  const header = input.description ? [input.description.replace(/\s+/g, ' ').trim()] : []
  let content: string
  try {
    content = generateSkript(input.function_name, plan, header)
  } catch (error) {
    if (error instanceof GeometryError) throw new ToolError(error.message)
    throw error
  }
  return { content, summary: report(scene, plan) }
}

export const writeDisplayScriptTool = defineTool<WriteScriptInput>({
  name: 'write_display_script',
  description:
    'Compile a drawing (same shapes as display_geometry) and write it as a self-contained .sk file defining ' +
    '`<function_name>(origin: location, yaw: number = 0) :: entities`, which spawns the block displays with the drawing\'s ' +
    'local (0, 0, 0) at origin and returns them. yaw turns the drawing around the vertical axis so local +z points where an ' +
    'entity with that yaw looks (pass the player\'s yaw to face them). Call the function from other scripts; do not copy or ' +
    'edit the generated numbers. Only files generated by this tool can be overwritten.',
  inputSchema: {
    type: 'object',
    properties: {
      path: { type: 'string', description: 'New or empty .sk file relative to the project root, e.g. drawings/house.sk.' },
      function_name: { type: 'string', description: 'Skript function name (letters, digits, _), e.g. draw_house.' },
      description: { type: 'string', description: 'One line stored as a comment at the top of the file.' },
      ...sceneProperties
    },
    required: ['path', 'function_name', 'shapes'],
    additionalProperties: false
  },
  permission: 'write',
  async preview(input, ctx) {
    const { before } = await generatedTarget(ctx, input.path, SCRIPT_MARKER)
    const { content } = await buildScript(input, ctx)
    return {
      summary: `${before === null ? 'Create' : 'Regenerate'} ${input.path} (display drawing ${input.function_name})`,
      changes: [{ path: input.path, before: before ?? '', after: content, created: before === null }]
    }
  },
  async execute(input, ctx) {
    const { file, before } = await generatedTarget(ctx, input.path, SCRIPT_MARKER)
    const { content, summary } = await buildScript(input, ctx)
    await mkdir(dirname(file), { recursive: true })
    await writeFile(file, content, 'utf8')
    ctx.onFilesChanged?.([{ path: input.path, before: before ?? '', after: content, created: before === null }])
    return [
      `${before === null ? 'Created' : 'Regenerated'} ${input.path}: function ${input.function_name}(origin: location, yaw: number = 0) :: entities.`,
      ...summary
    ].join('\n')
  }
})

export const writeDisplayLibraryTool = defineTool<{ path?: string }>({
  name: 'write_display_library',
  description:
    'Write the display math library (.sk) to the project for drawings whose positions are only known at runtime ' +
    '(a beam between two players, a shape around a moving entity, rotating/animating spawned displays). Functions:\n' +
    LIBRARY_FUNCTIONS.map((fn) => `- ${fn.signature}: ${fn.doc}`).join('\n') +
    '\nVectors are relative to origin unless stated. Use these instead of writing rotation/quaternion math in Skript yourself.',
  inputSchema: {
    type: 'object',
    properties: { path: { type: 'string', description: 'Default: display-lib.sk' } },
    additionalProperties: false
  },
  permission: 'write',
  async preview({ path = 'display-lib.sk' }, ctx) {
    const { before } = await generatedTarget(ctx, path, LIBRARY_MARKER)
    return {
      summary: `${before === null ? 'Create' : 'Update'} ${path} (display math library)`,
      changes: [{ path, before: before ?? '', after: librarySource(), created: before === null }]
    }
  },
  async execute({ path = 'display-lib.sk' }, ctx) {
    const { file, before } = await generatedTarget(ctx, path, LIBRARY_MARKER)
    const content = librarySource()
    if (before === content) return `${path} is already up to date.`
    await mkdir(dirname(file), { recursive: true })
    await writeFile(file, content, 'utf8')
    ctx.onFilesChanged?.([{ path, before: before ?? '', after: content, created: before === null }])
    return `${before === null ? 'Created' : 'Updated'} ${path} with ${LIBRARY_FUNCTIONS.length} functions.`
  }
})

export const mathEvalTool = defineTool<{ expression: string }>({
  name: 'math_eval',
  description:
    'Evaluate math exactly instead of computing in your head: numbers, vectors [x, y, z], quaternions [w, x, y, z], ' +
    'variables (`a = [1, 2, 3]`) and statements separated by `;` or new lines. Operators + - * / % ^ (element-wise on vectors), ' +
    'indexing v[0]. Constants pi, tau, e. Functions: ' +
    Object.entries(FUNCTIONS).map(([name, { doc }]) => (doc ? `${name} (${doc})` : name)).join(', ') +
    '. Minecraft yaw: 0 = south (+z), 90 = west (-x); pitch: -90 = up.',
  inputSchema: {
    type: 'object',
    properties: { expression: { type: 'string', description: 'e.g. "a = [0,0,0]; b = [3,4,0]; dist(a, b); angled(b, [1,0,0])"' } },
    required: ['expression'],
    additionalProperties: false
  },
  permission: 'read',
  async execute({ expression }) {
    try {
      return evaluate(expression)
        .map(({ name, value }) => (name ? `${name} = ${formatValue(value)}` : formatValue(value)))
        .join('\n')
    } catch (error) {
      if (error instanceof ExprError) throw new ToolError(error.message)
      throw error
    }
  }
})

