/**
 * Parça (paralelyüz) → Minecraft display dönüşümü ve Skript kodu.
 *
 * Minecraft bir display'in modelini `T · L · S · R` ile dönüştürür (öteleme, sol dönüş, ölçek, sağ dönüş);
 * block display'in modeli birim küp (0..1)³'tür. Parçanın kenar matrisi `E = U·Σ·Vᵀ` (SVD) olarak ayrılınca
 * `L = U`, `S = Σ`, `R = Vᵀ` olur; böylece eğme (shear) dahil her afin paralelyüz tam olarak yazılabilir.
 */

import {
  add,
  apply,
  diag,
  distance,
  formatNumber,
  IDENTITY_QUAT,
  matToQuat,
  mul,
  quatToMat,
  roundTo,
  svd,
  transpose,
  type Quat,
  type Vec3
} from './math'
import { GeometryError, partCorners, type Part } from './shapes'

export interface DisplayTransform {
  block: string
  source: string
  translation: Vec3
  left: Quat
  scale: Vec3
  right: Quat
}

/** Kodda yazılan ondalık basamaklar; float'ın ~7 anlamlı basamağıyla uyumlu. */
const POSITION_DECIMALS = 6
const ROTATION_DECIMALS = 7

export function toDisplayTransform(part: Part): DisplayTransform {
  const { u, sigma, v } = svd(part.edges)
  if (sigma[2] <= 0) throw new GeometryError(`${part.source}: degenerate part (zero thickness).`)
  let right = matToQuat(transpose(v))
  // Eğme yoksa sağ dönüş birimdir; kodu sade tutmak için tam birime yuvarla
  if (Math.abs(right.x) < 1e-10 && Math.abs(right.y) < 1e-10 && Math.abs(right.z) < 1e-10) right = IDENTITY_QUAT
  return {
    block: part.block,
    source: part.source,
    translation: part.origin.map((n) => roundTo(n, POSITION_DECIMALS)) as unknown as Vec3,
    left: roundQuat(matToQuat(u)),
    scale: sigma.map((n) => roundTo(n, POSITION_DECIMALS)) as unknown as Vec3,
    right: roundQuat(right)
  }
}

function roundQuat(q: Quat): Quat {
  return {
    w: roundTo(q.w, ROTATION_DECIMALS),
    x: roundTo(q.x, ROTATION_DECIMALS),
    y: roundTo(q.y, ROTATION_DECIMALS),
    z: roundTo(q.z, ROTATION_DECIMALS)
  }
}

const f32 = Math.fround
const f32Vec = (v: Vec3): Vec3 => [f32(v[0]), f32(v[1]), f32(v[2])]
const f32Quat = (q: Quat): Quat => ({ w: f32(q.w), x: f32(q.x), y: f32(q.y), z: f32(q.z) })

/**
 * Yazılan (yuvarlanmış) değerlerden, oyunun yapacağı gibi `float` ile küpün 8 köşesini yeniden hesaplar
 * ve hedef paralelyüzün köşelerinden en büyük uzaklığı döndürür (blok).
 */
export function cornerError(part: Part, transform: DisplayTransform): number {
  const m = mul(mul(quatToMat(f32Quat(transform.left)), diag(f32Vec(transform.scale))), quatToMat(f32Quat(transform.right)))
  const t = f32Vec(transform.translation)
  const expected = partCorners(part)
  let worst = 0
  for (let i = 0; i < 8; i++) {
    const c: Vec3 = [i & 1 ? 1 : 0, i & 2 ? 1 : 0, i & 4 ? 1 : 0]
    worst = Math.max(worst, distance(add(t, apply(m, c)), expected[i]))
  }
  return worst
}

/** Bu değeri aşan sapma bir hatadır (kod üretilmez). */
export const MAX_CORNER_ERROR = 1e-4

export interface DisplayPlan {
  transforms: DisplayTransform[]
  maxError: number
}

export function planDisplays(parts: readonly Part[]): DisplayPlan {
  const transforms: DisplayTransform[] = []
  let maxError = 0
  for (const part of parts) {
    const transform = toDisplayTransform(part)
    const error = cornerError(part, transform)
    if (!(error <= MAX_CORNER_ERROR)) {
      throw new GeometryError(`${part.source}: internal check failed, corner error ${error.toExponential(2)} blocks.`)
    }
    maxError = Math.max(maxError, error)
    transforms.push(transform)
  }
  return { transforms, maxError }
}

// --- Skript kodu ---

const FUNCTION_NAME = /^[A-Za-z_][A-Za-z0-9_]{0,48}$/
const BLOCK = /^[a-z0-9_:]+(\[[a-z0-9_=,;:\- ]*\])?$/

export function checkFunctionName(name: string): void {
  if (!FUNCTION_NAME.test(name)) throw new GeometryError(`function_name must match ${FUNCTION_NAME.source}.`)
}

export function checkBlock(block: string, source: string): void {
  if (!BLOCK.test(block)) throw new GeometryError(`${source}: block "${block}" must be a block id such as white_concrete or oak_stairs[facing=north].`)
}

const n6 = (value: number): string => formatNumber(value, POSITION_DECIMALS)
const n7 = (value: number): string => formatNumber(value, ROTATION_DECIMALS)

/**
 * Kendi kendine yeten Skript kodu: `name(origin, yaw)` çizimi oluşturur ve display'leri döndürür,
 * `name_part` tek display'i kurar. `yaw` (derece, Minecraft yönü) tüm çizimi köken etrafında döndürür:
 * yerel +z, o yaw ile bakan bir varlığın baktığı yöne gelir (0 = güney/+z, 90 = batı/-x).
 */
export function generateSkript(name: string, plan: DisplayPlan, header: string[] = []): string {
  checkFunctionName(name)
  for (const t of plan.transforms) checkBlock(t.block, t.source)
  const part = `${name}_part`
  const lines: string[] = [
    `# ${name}: generated by Skript IDE (display_geometry). Do not edit the numbers by hand; regenerate instead.`,
    `# ${plan.transforms.length} block displays; max corner error ${plan.maxError.toExponential(1)} blocks (float precision).`,
    ...header.map((line) => `# ${line}`),
    `# ${name}(origin, yaw) spawns the drawing with its local (0, 0, 0) at origin and returns the displays`,
    '# (delete them later with: kill {_displays::*}). yaw rotates it around the vertical axis: local +z',
    '# points where an entity with that yaw looks (0 = south/+z, 90 = west/-x).',
    `function ${name}(origin: location, yaw: number = 0) :: entities:`,
    '\tset {_o} to {_origin}',
    '\t# The display\'s own yaw/pitch would rotate the whole transformation',
    '\tset yaw of {_o} to 0',
    '\tset pitch of {_o} to 0'
  ]
  for (const t of plan.transforms) {
    const args = [
      `"${t.block}"`,
      ...t.translation.map(n6),
      n7(t.left.w), n7(t.left.x), n7(t.left.y), n7(t.left.z),
      ...t.scale.map(n6),
      n7(t.right.w), n7(t.right.x), n7(t.right.y), n7(t.right.z)
    ]
    lines.push(`\tadd ${part}({_o}, {_yaw}, ${args.join(', ')}) to {_displays::*}`)
  }
  lines.push(
    '\treturn {_displays::*}',
    '',
    `# One block display: translation t, left rotation l, scale s, right rotation r (Minecraft order T·L·S·R).`,
    `function ${part}(o: location, yaw: number, block: text, tx: number, ty: number, tz: number, lw: number, lx: number, ly: number, lz: number, sx: number, sy: number, sz: number, rw: number, rx: number, ry: number, rz: number) :: entity:`,
    '\tset {_c} to cos({_yaw})',
    '\tset {_s} to sin({_yaw})',
    '\tset {_hc} to cos({_yaw} / 2)',
    '\tset {_hs} to sin({_yaw} / 2)',
    '\tspawn block display at {_o}',
    '\tset {_d} to last spawned entity',
    '\tset block data of {_d} to {_block} parsed as block data',
    '\tset display translation of {_d} to vector({_tx} * {_c} - {_tz} * {_s}, {_ty}, {_tx} * {_s} + {_tz} * {_c})',
    '\tset left rotation of {_d} to quaternion({_hc} * {_lw} + {_hs} * {_ly}, {_hc} * {_lx} - {_hs} * {_lz}, {_hc} * {_ly} - {_hs} * {_lw}, {_hc} * {_lz} + {_hs} * {_lx})',
    '\tset display scale of {_d} to vector({_sx}, {_sy}, {_sz})',
    '\tset right rotation of {_d} to quaternion({_rw}, {_rx}, {_ry}, {_rz})',
    '\treturn {_d}',
    ''
  )
  return lines.join('\n')
}

/** Kod yerine ham değerler: her display için `translation`, `left_rotation` (w,x,y,z), `scale`, `right_rotation`. */
export function transformsTable(plan: DisplayPlan): string {
  return plan.transforms
    .map((t, i) => {
      const q = (r: Quat): string => `(${n7(r.w)}, ${n7(r.x)}, ${n7(r.y)}, ${n7(r.z)})`
      return `${i + 1}. ${t.source} [${t.block}] translation=(${t.translation.map(n6).join(', ')}) left_rotation=${q(t.left)} scale=(${t.scale.map(n6).join(', ')}) right_rotation=${q(t.right)}`
    })
    .join('\n')
}
