/** Kütüphanenin Skript kaynağı. Sabit metindir; sürüm değiştikçe `LIBRARY_VERSION` artırılır. */
export function librarySource(): string {
  return `# Display math library v${LIBRARY_VERSION}: ${LIBRARY_MARKER}. Do not edit by hand.
# Exact runtime math for block displays. Angles are in degrees; quaternions are quaternion(w, x, y, z).
# A block display shows the unit cube (0..1)^3 transformed by T·L·S·R:
# translation, left rotation, scale, right rotation.

# Product a·b: rotating by the result = rotating by b, then by a.
function dg_qmul(a: quaternion, b: quaternion) :: quaternion:
	set {_aw} to the w component of {_a}
	set {_ax} to the x component of {_a}
	set {_ay} to the y component of {_a}
	set {_az} to the z component of {_a}
	set {_bw} to the w component of {_b}
	set {_bx} to the x component of {_b}
	set {_by} to the y component of {_b}
	set {_bz} to the z component of {_b}
	return quaternion({_aw} * {_bw} - {_ax} * {_bx} - {_ay} * {_by} - {_az} * {_bz}, {_aw} * {_bx} + {_ax} * {_bw} + {_ay} * {_bz} - {_az} * {_by}, {_aw} * {_by} - {_ax} * {_bz} + {_ay} * {_bw} + {_az} * {_bx}, {_aw} * {_bz} + {_ax} * {_by} - {_ay} * {_bx} + {_az} * {_bw})

# Rotation around an axis by the right-hand rule.
function dg_axis_angle(axis: vector, degrees: number) :: quaternion:
	set {_x} to the x component of {_axis}
	set {_y} to the y component of {_axis}
	set {_z} to the z component of {_axis}
	set {_n} to sqrt({_x} * {_x} + {_y} * {_y} + {_z} * {_z})
	set {_s} to sin({_degrees} / 2) / {_n}
	return quaternion(cos({_degrees} / 2), {_x} * {_s}, {_y} * {_s}, {_z} * {_s})

function dg_rotate(v: vector, q: quaternion) :: vector:
	set {_w} to the w component of {_q}
	set {_qx} to the x component of {_q}
	set {_qy} to the y component of {_q}
	set {_qz} to the z component of {_q}
	set {_x} to the x component of {_v}
	set {_y} to the y component of {_v}
	set {_z} to the z component of {_v}
	# v' = v + 2w(q × v) + 2 q × (q × v)
	set {_cx} to {_qy} * {_z} - {_qz} * {_y}
	set {_cy} to {_qz} * {_x} - {_qx} * {_z}
	set {_cz} to {_qx} * {_y} - {_qy} * {_x}
	set {_dx} to {_qy} * {_cz} - {_qz} * {_cy}
	set {_dy} to {_qz} * {_cx} - {_qx} * {_cz}
	set {_dz} to {_qx} * {_cy} - {_qy} * {_cx}
	return vector({_x} + 2 * ({_w} * {_cx} + {_dx}), {_y} + 2 * ({_w} * {_cy} + {_dy}), {_z} + 2 * ({_w} * {_cz} + {_dz}))

# Turns local +z to where an entity with this Minecraft yaw looks (0 = south/+z, 90 = west/-x).
function dg_yaw(yaw: number) :: quaternion:
	return quaternion(cos({_yaw} / 2), 0, sin({_yaw} / 2) * -1, 0)

# Rotation mapping the x, y, z axes to the given orthonormal right-handed axes (Shepperd's method).
function dg_frame(x: vector, y: vector, z: vector) :: quaternion:
	set {_m00} to the x component of {_x}
	set {_m10} to the y component of {_x}
	set {_m20} to the z component of {_x}
	set {_m01} to the x component of {_y}
	set {_m11} to the y component of {_y}
	set {_m21} to the z component of {_y}
	set {_m02} to the x component of {_z}
	set {_m12} to the y component of {_z}
	set {_m22} to the z component of {_z}
	set {_trace} to {_m00} + {_m11} + {_m22}
	if {_trace} > 0:
		set {_s} to sqrt({_trace} + 1) * 2
		return quaternion({_s} / 4, ({_m21} - {_m12}) / {_s}, ({_m02} - {_m20}) / {_s}, ({_m10} - {_m01}) / {_s})
	if {_m00} > {_m11}:
		if {_m00} > {_m22}:
			set {_s} to sqrt(1 + {_m00} - {_m11} - {_m22}) * 2
			return quaternion(({_m21} - {_m12}) / {_s}, {_s} / 4, ({_m01} + {_m10}) / {_s}, ({_m02} + {_m20}) / {_s})
	if {_m11} > {_m22}:
		set {_s} to sqrt(1 + {_m11} - {_m00} - {_m22}) * 2
		return quaternion(({_m02} - {_m20}) / {_s}, ({_m01} + {_m10}) / {_s}, {_s} / 4, ({_m12} + {_m21}) / {_s})
	set {_s} to sqrt(1 + {_m22} - {_m00} - {_m11}) * 2
	return quaternion(({_m10} - {_m01}) / {_s}, ({_m02} + {_m20}) / {_s}, ({_m12} + {_m21}) / {_s}, {_s} / 4)

# One block display with transformation T·L·S·R. The location's own yaw/pitch would rotate everything, so they are reset.
function dg_spawn(origin: location, block: text, t: vector, l: quaternion, s: vector, r: quaternion) :: entity:
	set {_o} to {_origin}
	set yaw of {_o} to 0
	set pitch of {_o} to 0
	spawn block display at {_o}
	set {_d} to last spawned entity
	set block data of {_d} to {_block} parsed as block data
	set display translation of {_d} to {_t}
	set left rotation of {_d} to {_l}
	set display scale of {_d} to {_s}
	set right rotation of {_d} to {_r}
	return {_d}

# Box with its center relative to origin.
function dg_box(origin: location, block: text, center: vector, size: vector, rotation: quaternion) :: entity:
	set {_half} to dg_rotate({_size} * vector(0.5, 0.5, 0.5), {_rotation})
	return dg_spawn({_origin}, {_block}, {_center} - {_half}, {_rotation}, {_size}, quaternion(1, 0, 0, 0))

# Square bar from a to b (relative to origin); the width axis is horizontal.
function dg_line(origin: location, block: text, a: vector, b: vector, width: number) :: entity:
	set {_d} to {_b} - {_a}
	set {_len} to sqrt((the x component of {_d}) ^ 2 + (the y component of {_d}) ^ 2 + (the z component of {_d}) ^ 2)
	set {_dir} to {_d} * vector(1 / {_len}, 1 / {_len}, 1 / {_len})
	# side = normalize(up × dir); vertical bars use +x
	set {_hx} to the z component of {_dir}
	set {_hz} to (the x component of {_dir}) * -1
	set {_h} to sqrt({_hx} * {_hx} + {_hz} * {_hz})
	if {_h} > 0.000001:
		set {_side} to vector({_hx} / {_h}, 0, {_hz} / {_h})
	else:
		set {_side} to vector(1, 0, 0)
	set {_dx} to the x component of {_dir}
	set {_dy} to the y component of {_dir}
	set {_dz} to the z component of {_dir}
	set {_sx} to the x component of {_side}
	set {_sy} to the y component of {_side}
	set {_sz} to the z component of {_side}
	# up = dir × side keeps the frame right-handed
	set {_up} to vector({_dy} * {_sz} - {_dz} * {_sy}, {_dz} * {_sx} - {_dx} * {_sz}, {_dx} * {_sy} - {_dy} * {_sx})
	set {_offset} to ({_side} + {_up}) * vector({_width} / 2, {_width} / 2, {_width} / 2)
	return dg_spawn({_origin}, {_block}, {_a} - {_offset}, dg_frame({_dir}, {_side}, {_up}), vector({_len}, {_width}, {_width}), quaternion(1, 0, 0, 0))

# Square bar between two world locations, e.g. between two players.
function dg_beam(from: location, to: location, block: text, width: number) :: entity:
	return dg_line({_from}, {_block}, vector(0, 0, 0), vector((x coordinate of {_to}) - (x coordinate of {_from}), (y coordinate of {_to}) - (y coordinate of {_from}), (z coordinate of {_to}) - (z coordinate of {_from})), {_width})

# Flat plate with corner p and edges e1, e2 (relative to origin), centered on its plane.
# The 2x2 in-plane part is split exactly as Rot(phi)·diag(s1, s2)·Rot(theta) (closed-form SVD).
function dg_parallelogram(origin: location, block: text, p: vector, e1: vector, e2: vector, thickness: number) :: entity:
	set {_ax} to the x component of {_e1}
	set {_ay} to the y component of {_e1}
	set {_az} to the z component of {_e1}
	set {_bx} to the x component of {_e2}
	set {_by} to the y component of {_e2}
	set {_bz} to the z component of {_e2}
	set {_a} to sqrt({_ax} * {_ax} + {_ay} * {_ay} + {_az} * {_az})
	set {_nx} to {_ay} * {_bz} - {_az} * {_by}
	set {_ny} to {_az} * {_bx} - {_ax} * {_bz}
	set {_nz} to {_ax} * {_by} - {_ay} * {_bx}
	set {_area} to sqrt({_nx} * {_nx} + {_ny} * {_ny} + {_nz} * {_nz})
	set {_u} to vector({_ax} / {_a}, {_ay} / {_a}, {_az} / {_a})
	set {_n} to vector({_nx} / {_area}, {_ny} / {_area}, {_nz} / {_area})
	set {_ux} to the x component of {_u}
	set {_uy} to the y component of {_u}
	set {_uz} to the z component of {_u}
	set {_nx} to the x component of {_n}
	set {_ny} to the y component of {_n}
	set {_nz} to the z component of {_n}
	set {_v} to vector({_ny} * {_uz} - {_nz} * {_uy}, {_nz} * {_ux} - {_nx} * {_uz}, {_nx} * {_uy} - {_ny} * {_ux})
	# In the (u, v) frame: e1 = (a, 0), e2 = (b, c)
	set {_b} to {_bx} * {_ux} + {_by} * {_uy} + {_bz} * {_uz}
	set {_c} to {_area} / {_a}
	set {_e} to ({_a} + {_c}) / 2
	set {_f} to ({_a} - {_c}) / 2
	set {_g} to {_b} / 2
	set {_h} to {_b} / -2
	set {_q} to sqrt({_e} * {_e} + {_h} * {_h})
	set {_r} to sqrt({_f} * {_f} + {_g} * {_g})
	set {_a1} to dg_atan2({_g}, {_f})
	set {_a2} to dg_atan2({_h}, {_e})
	set {_theta} to ({_a2} - {_a1}) / 2
	set {_phi} to ({_a2} + {_a1}) / 2
	set {_left} to dg_qmul(dg_frame({_u}, {_v}, {_n}), quaternion(cos({_phi} / 2), 0, 0, sin({_phi} / 2)))
	set {_right} to quaternion(cos({_theta} / 2), 0, 0, sin({_theta} / 2))
	set {_t} to {_p} - {_n} * vector({_thickness} / 2, {_thickness} / 2, {_thickness} / 2)
	return dg_spawn({_origin}, {_block}, {_t}, {_left}, vector({_q} + {_r}, {_q} - {_r}, {_thickness}), {_right})

# atan2 in degrees with the usual (y, x) argument order; Skript's atan2 takes the point as (x, y).
function dg_atan2(y: number, x: number) :: number:
	return atan2({_x}, {_y})

# Filled triangle: the union of 3 parallelograms from each corner to the edge midpoints.
# Their thicknesses differ by 0.001 so overlapping faces do not flicker.
function dg_triangle(origin: location, block: text, a: vector, b: vector, c: vector, thickness: number) :: entities:
	set {_h} to vector(0.5, 0.5, 0.5)
	add dg_parallelogram({_origin}, {_block}, {_a}, ({_b} - {_a}) * {_h}, ({_c} - {_a}) * {_h}, {_thickness}) to {_parts::*}
	add dg_parallelogram({_origin}, {_block}, {_b}, ({_c} - {_b}) * {_h}, ({_a} - {_b}) * {_h}, {_thickness} + 0.001) to {_parts::*}
	add dg_parallelogram({_origin}, {_block}, {_c}, ({_a} - {_c}) * {_h}, ({_b} - {_c}) * {_h}, {_thickness} + 0.002) to {_parts::*}
	return {_parts::*}

# Rotates spawned displays around their own entity location (where the drawing's origin is).
# With a duration the client animates the turn smoothly.
function dg_turn(displays: entities, rotation: quaternion, duration: timespan = 0 ticks):
	loop {_displays::*}:
		set interpolation duration of loop-value to {_duration}
		set display translation of loop-value to dg_rotate(display translation of loop-value, {_rotation})
		set left rotation of loop-value to dg_qmul({_rotation}, left rotation of loop-value)
		set interpolation delay of loop-value to 0 ticks
`
}
